// Every tunable number the engine uses. All are user-editable; Evidence-tagged values show a
// warning when set outside `evidenceRange`. Stored values are merged over these defaults on read,
// so adding a key never needs a migration.

export type SettingTag = 'Evidence' | 'Heuristic'

export type SettingGroup =
  | 'energy'
  | 'rateBands'
  | 'macros'
  | 'checkin'
  | 'body'
  | 'phases'
  | 'volume'
  | 'progression'
  | 'deload'
  | 'app'

export interface SettingMeta {
  readonly key: string
  readonly label: string
  readonly group: SettingGroup
  readonly tag: SettingTag
  readonly unit: string
  readonly default: number
  readonly min: number
  readonly max: number
  readonly step: number
  /** Range backed by the cited evidence; only for Evidence-tagged settings. */
  readonly evidenceRange?: readonly [number, number]
  readonly help: string
}

